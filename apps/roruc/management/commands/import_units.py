"""
Import units from the legacy MySQL exports.

Usage:
    python manage.py import_units all_units.tsv all_relations.tsv
    python manage.py import_units all_units.tsv all_relations.tsv --dry-run

Input files (tab-separated, NO header row, as exported):
    all_units.tsv       id <TAB> name <TAB> type <TAB> status
    all_relations.tsv   child_id <TAB> parent_id

How it maps onto the data model:
  * The legacy id (e.g. "aah") is stored as a UnitExternalIdentifier of type
    ESCHOLARSHIP and is the key used to find existing rows, so the command is
    idempotent. Unit.uid is generated by the model and never touched.
  * name is whitespace-stripped; type must be a valid UnitType value.
  * Legacy status is translated with STATUS_MAP (the legacy values are
    active / archived / hidden; the model has active / inactive / withdrawn).
  * Each relation row becomes a UnitHierarchyEdge(parent -> child). Units with
    several parents are fine; cycles are rejected by django-postgresql-dag.

All input is validated before anything is written. Everything is written in
one transaction; --dry-run rolls it back.
"""
import csv

from django.core.exceptions import ValidationError
from django.core.management.base import BaseCommand, CommandError
from django.db import IntegrityError, transaction

from ...models import (
    ExternalIdentifierType,
    Unit,
    UnitExternalIdentifier,
    UnitHierarchyEdge,
    UnitStatus,
    UnitType,
)

LEGACY_ID = ExternalIdentifierType.ESCHOLARSHIP

# Legacy status -> UnitStatus. "hidden" has no direct equivalent in the model;
# change this (or add a HIDDEN choice to UnitStatus) if you want to preserve it.
STATUS_MAP = {
    "active": UnitStatus.ACTIVE,
    "archived": UnitStatus.INACTIVE,
    "hidden": UnitStatus.INACTIVE,
}


# --------------------------------------------------------------------------- #
# Parsing / validation (no database access)
# --------------------------------------------------------------------------- #
def read_tsv(path, ncols):
    rows = []
    try:
        with open(path, newline="", encoding="utf-8") as fh:
            reader = csv.reader(fh, delimiter="\t", quoting=csv.QUOTE_NONE)
            for lineno, row in enumerate(reader, start=1):
                if not row or all(not c.strip() for c in row):
                    continue
                if len(row) != ncols:
                    raise CommandError(
                        f"{path}:{lineno}: expected {ncols} tab-separated columns, got {len(row)}"
                    )
                rows.append([c.strip() for c in row])
    except OSError as exc:
        raise CommandError(f"Cannot read {path}: {exc}")
    return rows


def parse_and_validate(units_path, relations_path):
    """Return (units, edges). units: {legacy_id: {name,type,status}}, edges: sorted [(parent, child)].
    Raises CommandError listing every problem found."""
    errors = []
    units = {}

    for uid, name, utype, status in read_tsv(units_path, 4):
        if uid in units:
            errors.append(f"duplicate unit id: {uid}")
            continue
        if not name:
            errors.append(f"unit {uid}: empty name")
        if utype not in UnitType.values:
            errors.append(f"unit {uid}: unknown type {utype!r}")
        if status not in STATUS_MAP:
            errors.append(f"unit {uid}: unknown status {status!r}")
        units[uid] = {"name": name, "type": utype, "status": STATUS_MAP.get(status)}

    edges = set()
    for child, parent in read_tsv(relations_path, 2):
        if child == parent:
            errors.append(f"relation {child} -> itself")
        elif child not in units:
            errors.append(f"relation references unknown child {child!r}")
        elif parent not in units:
            errors.append(f"relation references unknown parent {parent!r}")
        else:
            edges.add((parent, child))

    if errors:
        shown = "\n  ".join(errors[:40])
        more = f"\n  ...and {len(errors) - 40} more" if len(errors) > 40 else ""
        raise CommandError(f"{len(errors)} problem(s) in input:\n  {shown}{more}")

    return units, sorted(edges)


# --------------------------------------------------------------------------- #
# Command
# --------------------------------------------------------------------------- #
class Command(BaseCommand):
    help = "Import units and their hierarchy from the legacy MySQL TSV exports."

    def add_arguments(self, parser):
        parser.add_argument("units_file", help="all_units.tsv (id, name, type, status)")
        parser.add_argument("relations_file", help="all_relations.tsv (child_id, parent_id)")
        parser.add_argument("--dry-run", action="store_true", help="Process, then roll back.")

    def handle(self, *args, **opts):
        units, edges = parse_and_validate(opts["units_file"], opts["relations_file"])
        self.stdout.write(f"Read {len(units)} units and {len(edges)} parent/child relations.")

        created = updated = unchanged = edges_added = edges_existing = edges_failed = 0

        with transaction.atomic():
            # ---- Pass 1: units -------------------------------------------------
            by_legacy = {
                e.value: e.unit
                for e in UnitExternalIdentifier.objects.filter(
                    type=LEGACY_ID, value__in=list(units)
                ).select_related("unit")
            }

            for legacy_id, d in units.items():
                unit = by_legacy.get(legacy_id)
                if unit is None:
                    unit = Unit(name=d["name"], type=d["type"], status=d["status"])
                    unit.save()
                    UnitExternalIdentifier.objects.create(
                        unit=unit, type=LEGACY_ID, value=legacy_id
                    )
                    by_legacy[legacy_id] = unit
                    created += 1
                elif (unit.name, unit.type, unit.status) != (d["name"], d["type"], d["status"]):
                    unit.name, unit.type, unit.status = d["name"], d["type"], d["status"]
                    unit.save()
                    updated += 1
                else:
                    unchanged += 1

            # ---- Pass 2: hierarchy --------------------------------------------
            existing = set(
                UnitHierarchyEdge.objects.filter(
                    parent__in=[u.pk for u in by_legacy.values()]
                ).values_list("parent_id", "child_id")
            )
            for parent_id, child_id in edges:
                parent, child = by_legacy[parent_id], by_legacy[child_id]
                if (parent.pk, child.pk) in existing:
                    edges_existing += 1
                    continue
                try:
                    with transaction.atomic():  # savepoint: one bad edge doesn't abort the import
                        UnitHierarchyEdge(parent=parent, child=child).save()
                    edges_added += 1
                except (ValidationError, IntegrityError) as exc:
                    self.stderr.write(self.style.WARNING(
                        f"Could not add {parent_id} -> {child_id}: {exc}"
                    ))
                    edges_failed += 1

            if opts["dry_run"]:
                transaction.set_rollback(True)
                self.stdout.write(self.style.WARNING("Dry run: changes rolled back."))

        self.stdout.write(self.style.SUCCESS(
            f"Units: {created} created, {updated} updated, {unchanged} unchanged. "
            f"Edges: {edges_added} added, {edges_existing} already present, {edges_failed} failed."
        ))